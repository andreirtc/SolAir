  assert.equal(receiver.snapshot().state.acceptedCount, stable.state.acceptedCount);
  assert.equal(receiver.history().find(r => r.message.sequence === 0).acceptedRetryCount, 2);
  assert.equal(deviceConnectionState(emptyDiagnostics('ET-01'), clock).status, 'NEVER CONNECTED');
  const receiptMs = Date.parse(receiver.snapshot().state.heartbeat.receivedAtUtc);
  for (const [age, status] of [[14999, 'ONLINE'], [15000, 'STALE'], [29999, 'STALE'], [30000, 'OFFLINE']]) assert.equal(deviceConnectionState(receiver.snapshot().state, receiptMs + age).status, status);
  assert.equal(deviceConnectionState(receiver.snapshot().state, receiptMs + 6000, 2000).status, 'STALE');
  const credentials = await createTestOperator(join(directory, 'auth.sqlite'));
  const foreign = await createTestOperator(join(directory, 'auth.sqlite'), 'other', 'OTHER');
  const hosts = [];

  // SSE reconnection sends the current durable snapshot, without ingestion or age refresh.
  for (let n = 0; n < 2; n++) {
    const response = await fetch(base + '/api/diagnostics/stream', { headers }); const reader = response.body.getReader();
    const frame = new TextDecoder().decode((await reader.read()).value);
    assert.match(frame, /TEST FIXTURE/); assert.match(frame, new RegExp(secondBoot.sessionId)); await reader.cancel();
  }
  assert.deepEqual(receiver.snapshot(), stable);
  console.log('PASS software hardening: fixture provenance, tokens/identity/schema, exact/conflicting/stale retries, boots, historical events, restart, rollback, REAL export/ACL/pagination/null/zero/CSV safety, SSE reconnect, connection boundaries. No physical testing.');
